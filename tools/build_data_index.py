#!/usr/bin/env python3
"""
build_data_index.py - Generate a grep-ready DATA_INDEX.md for a persona from Hatch app-data.

Usage:
    python3 tools/build_data_index.py persona/arjun-mehra_omni-hi-sg-01

Reads  <persona>/app-data/apps/*/raw-state.json
Writes <persona>/DATA_INDEX.md

Why: before writing any prompt, the agent must ground it in records that EXIST.
This index lets you grep titles, dates, names, and amounts in seconds instead of
unzipping and hunting. Re-run whenever the app export is refreshed.
"""
import json, sys, os, re
from pathlib import Path
from collections import defaultdict

def load(app_dir):
    p = app_dir / "raw-state.json"
    if not p.exists():
        return None
    with open(p) as f:
        return json.load(f)

def table(d, name):
    for t in d.get("tables", []):
        if t["name"] == name:
            return t.get("rows", [])
    return []

def s(v, n=110):
    v = "" if v is None else str(v).replace("\n", " ")
    return v if len(v) <= n else v[:n-1] + "…"

def main(persona_dir):
    persona_dir = Path(persona_dir)
    apps_dir = persona_dir / "app-data" / "apps"
    out = []
    A = out.append
    A("# DATA_INDEX — grep-ready index of persona records\n")
    A("> GENERATED by tools/build_data_index.py. Do not hand-edit; re-run the tool after a new app export.")
    A("> Purpose: ground every prompt in records that exist. Search this file first, then open the raw app-data if you need exact cells.\n")
    A(f"Source: `{apps_dir.relative_to(persona_dir)}` (raw-state.json per app)\n")

    for app_dir in sorted(apps_dir.iterdir()):
        if not app_dir.is_dir():
            continue
        d = load(app_dir)
        if not d:
            continue
        name = app_dir.name
        A(f"\n---\n## {name}\n")
        tnames = [t["name"] for t in d.get("tables", [])]
        A("Tables: " + ", ".join(f"`{t}`({next((x.get('row_count') for x in d['tables'] if x['name']==t), '?')})" for t in tnames) + "\n")

        if "gmail" in name:
            msgs = table(d, "gmail_messages")
            A(f"### Gmail messages ({len(msgs)}) — date | from | subject")
            for r in sorted(msgs, key=lambda r: str(r.get("date") or r.get("internal_date") or ""), reverse=True):
                A(f"- {s(r.get('date') or r.get('internal_date'),19)} | {s(r.get('from_email') or r.get('sender') or r.get('from'),35)} | {s(r.get('subject'),80)}")
        elif "outlook" in name:
            msgs = table(d, "outlook_messages")
            A(f"### Outlook messages ({len(msgs)}) — date | from | subject")
            for r in sorted(msgs, key=lambda r: str(r.get("received_at") or r.get("sent_at") or ""), reverse=True):
                A(f"- {s(r.get('received_at') or r.get('sent_at'),19)} | {s(r.get('from_email') or r.get('sender_email') or r.get('from_name'),35)} | {s(r.get('subject'),80)}")
        elif "contacts" in name:
            rows = table(d, "google_contacts")
            A(f"### Contacts ({len(rows)}) — name | relationship/notes")
            for r in rows:
                nm = r.get("display_name") or f"{r.get('given_name','')} {r.get('family_name','')}".strip()
                A(f"- {s(nm,40)} | {s(r.get('relationship') or r.get('notes') or r.get('label') or r.get('organization'),80)}")
        elif "calendar" in name:
            rows = table(d, "google_calendar_events")
            A(f"### Calendar events ({len(rows)}) — start | title | location")
            for r in sorted(rows, key=lambda r: str(r.get("start") or r.get("start_time") or "")):
                A(f"- {s(r.get('start') or r.get('start_time'),19)} | {s(r.get('summary') or r.get('title'),70)} | {s(r.get('location'),40)}")
        elif "drive" in name:
            rows = table(d, "google_drive_items")
            A(f"### Drive items ({len(rows)}) — name | type | modified")
            for r in rows:
                A(f"- {s(r.get('name') or r.get('title'),60)} | {s((r.get('mime_type') or '').split('/')[-1].replace('vnd.google-apps.',''),25)} | {s(r.get('modified_at') or r.get('updated_at'),19)}")
        elif "sheets" in name:
            ss = table(d, "google_sheets_spreadsheets")
            cells = table(d, "google_sheets_cells")
            bysheet = defaultdict(list)
            for c in cells:
                bysheet[c.get("spreadsheet_id")].append(c)
            A(f"### Spreadsheets ({len(ss)}) — title | updated | first rows preview")
            for r in ss:
                sid = r["id"]
                A(f"\n**{r.get('title')}** (`{sid}`, updated {s(r.get('updated_at'),10)})")
                rows = defaultdict(dict)
                for c in bysheet.get(sid, []):
                    rows[c.get("row_index", 0)][c.get("col_index", 0)] = c.get("value")
                for ri in sorted(rows)[:40]:
                    A("  - " + " | ".join(s(rows[ri].get(ci), 32) for ci in sorted(rows[ri])))
        elif "docs" in name:
            docs = table(d, "google_docs_documents")
            content = table(d, "google_docs_content")
            A(f"### Docs ({len(docs)}) — title + content")
            for r in docs:
                A(f"\n**{r.get('title')}** (`{r['id']}`)")
                for c in sorted([c for c in content if c.get("document_id") == r["id"]], key=lambda c: c.get("section_index", 0)):
                    A(f"  - {s(c.get('text_content'), 220)}")
        elif "whatsapp" in name:
            chats = table(d, "whatsapp_conversations") or table(d, "whatsapp_chats") or table(d, "chats")
            msgs = table(d, "whatsapp_messages") or table(d, "messages")
            users = {u.get("id"): (u.get("display_name") or u.get("name") or u.get("phone")) for u in table(d, "whatsapp_users")}
            A(f"### WhatsApp conversations ({len(chats)}) — name | type | last message date | msg count")
            last, count = {}, defaultdict(int)
            for m in msgs:
                cid = m.get("conversation_id") or m.get("chat_id")
                ts = str(m.get("timestamp") or m.get("sent_at") or m.get("created_at") or "")
                count[cid] += 1
                if ts > last.get(cid, ""):
                    last[cid] = ts
            for c in chats:
                nm = c.get("name") or c.get("title") or c.get("display_name") or users.get(c.get("peer_user_id")) or c.get("id")
                A(f"- {s(nm,45)} | {s(c.get('type') or c.get('conversation_type') or c.get('kind'),10)} | {s(last.get(c.get('id')),19)} | {count.get(c.get('id'),0)}")
            A(f"\n(Total messages: {len(msgs)}. Open raw-state.json → whatsapp_messages for content.)")
        elif "notion" in name:
            pages = table(d, "notion_pages")
            blocks = table(d, "notion_blocks")
            A(f"### Notion pages ({len(pages)}) — title + first blocks")
            for p in pages:
                A(f"\n**{p.get('title')}** (`{p['id']}`)")
                for b in sorted([b for b in blocks if b.get("parent_id") == p["id"]], key=lambda b: b.get("sort_order", 0))[:25]:
                    try:
                        txt = json.loads(b.get("content_json") or "{}").get("text", "")
                    except Exception:
                        txt = b.get("content_json")
                    if txt:
                        A(f"  - {s(txt, 160)}")
        elif "photos" in name:
            rows = table(d, "media_items") or table(d, "photos_media_items")
            A(f"### Photos ({len(rows)}) — date | description/filename")
            for r in sorted(rows, key=lambda r: str(r.get("creation_time") or r.get("taken_at") or ""))[:80]:
                A(f"- {s(r.get('creation_time') or r.get('taken_at'),19)} | {s(r.get('description') or r.get('filename') or r.get('caption'),90)}")
        elif "oura" in name:
            for t in d.get("tables", []):
                rows = t.get("rows", [])
                if not rows:
                    continue
                dates = [str(r.get("day") or r.get("date") or r.get("timestamp") or "") for r in rows]
                dates = [x for x in dates if x]
                A(f"- `{t['name']}`: {len(rows)} rows" + (f", {min(dates)[:10]} → {max(dates)[:10]}" if dates else ""))
            A("\nNOTE: Oura row date = WAKE-UP date. 'Night of 14th' is on row dated 15th.")
        elif "instagram" in name:
            for t in d.get("tables", []):
                rows = t.get("rows", [])
                A(f"- `{t['name']}`: {len(rows)} rows")
                for r in rows[:15]:
                    cap = r.get("caption") or r.get("text") or r.get("username") or r.get("name")
                    if cap:
                        A(f"    - {s(cap,120)}")
        elif "hue" in name:
            rooms = table(d, "hue_rooms"); lights = table(d, "hue_lights"); scenes = table(d, "hue_scenes")
            A(f"### Philips Hue — rooms {len(rooms)}, lights {len(lights)}, scenes {len(scenes)}")
            for r in rooms:
                A(f"- room: {s(r.get('name'),40)}")
            for r in lights:
                A(f"- light: {s(r.get('name'),40)} | on={r.get('on')} | room={s(r.get('room_id') or r.get('room'),20)}")
            for r in scenes:
                A(f"- scene: {s(r.get('name'),40)}")
        elif "nutrition" in name:
            for t in d.get("tables", []):
                rows = t.get("rows", [])
                if not rows:
                    continue
                dates = [str(r.get("date") or r.get("logged_at") or r.get("timestamp") or "") for r in rows]
                dates = [x for x in dates if x]
                A(f"- `{t['name']}`: {len(rows)} rows" + (f", {min(dates)[:10]} → {max(dates)[:10]}" if dates else ""))
        elif "healthex" in name:
            for t in d.get("tables", []):
                rows = t.get("rows", [])
                if not rows:
                    continue
                A(f"- `{t['name']}`: {len(rows)} rows")
                for r in rows[:8]:
                    nm = r.get("name") or r.get("display") or r.get("condition") or r.get("medication") or r.get("summary") or r.get("title")
                    if nm:
                        A(f"    - {s(nm,100)} | {s(r.get('date') or r.get('effective_date') or r.get('onset_date'),10)}")
        else:
            for t in d.get("tables", []):
                A(f"- `{t['name']}`: {t.get('row_count')} rows")

    (persona_dir / "DATA_INDEX.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {persona_dir/'DATA_INDEX.md'} ({len(out)} lines)")

if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(__doc__); sys.exit(1)
    main(sys.argv[1])
